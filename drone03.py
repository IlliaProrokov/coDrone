import time
from codrone_edu.drone import *

drone = Drone()
drone.pair()

# Тема "Пірати Карибського моря" (He's a Pirate)
# Формат: (частота Гц, тривалість звучання мс, пауза в секундах)

pirates_theme = [
    # Запеп / Запевна фанфара
    (440, 140, 0.02),  # A4
    (523, 140, 0.02),  # C5
    (587, 280, 0.04),  # D5
    (587, 140, 0.02),  # D5
    (587, 140, 0.02),  # D5
    (659, 140, 0.02),  # E5
    (698, 280, 0.04),  # F5
    (698, 140, 0.02),  # F5
    (698, 140, 0.02),  # F5
    (784, 140, 0.02),  # G5
    (659, 280, 0.04),  # E5
    (659, 140, 0.02),  # E5
    (587, 140, 0.02),  # D5
    (523, 140, 0.02),  # C5
    (587, 400, 0.15),  # D5 (акцент)

    # Друга частина фрази
    (440, 140, 0.02),  # A4
    (523, 140, 0.02),  # C5
    (587, 280, 0.04),  # D5
    (587, 140, 0.02),  # D5
    (587, 140, 0.02),  # D5
    (698, 140, 0.02),  # F5
    (784, 280, 0.04),  # G5
    (784, 140, 0.02),  # G5
    (784, 140, 0.02),  # G5
    (880, 140, 0.02),  # A5
    (698, 280, 0.04),  # F5
    (698, 140, 0.02),  # F5
    (587, 140, 0.02),  # D5
    (659, 140, 0.02),  # E5
    (587, 500, 0.20)   # D5 (фінал фрази)
]

# Піратські кольори (вогняно-червоний та золото)
colors = [
    (255, 30, 0),   # Червоний
    (255, 180, 0)   # Золотий
]

color_idx = 0

for freq, duration, pause in pirates_theme:
    # Зміна кольорів під кожний удар
    r, g, b = colors[color_idx % 2]
    drone.set_drone_LED(r, g, b, 100)
    
    drone.drone_buzzer(freq, duration)
    time.sleep(pause)
    
    color_idx += 1

drone.drone_LED_off()
drone.close()